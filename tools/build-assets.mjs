import {readFile,readdir,mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

const root=new URL('../',import.meta.url);
const names=['index.html','privacy.html','style.css','app.js','config.js','icon.svg','admin/index.html','admin/admin.css','admin/admin.js'];
const types={html:'text/html; charset=utf-8',css:'text/css; charset=utf-8',js:'text/javascript; charset=utf-8',svg:'image/svg+xml'};
const files={};
for(const name of names)files['/'+name]={type:types[name.split('.').at(-1)],body:await readFile(new URL('public/'+name,root),'utf8')};
const headerText=await readFile(new URL('public/_headers',root),'utf8');
const lines=headerText.trimEnd().split(/\r?\n/);
if(lines.shift()!=='/*')throw new Error('Static header rules need review.');
const headers={};
for(const line of lines){const match=/^  ([A-Za-z-]+): (.+)$/.exec(line);if(!match)throw new Error('Unsupported static header rule.');headers[match[1]]=match[2];}
const digest=createHash('sha256');
const sourceNames=(await readdir(new URL('src/',root))).filter(n=>n.endsWith('.mjs')).sort();
for(const name of [...sourceNames.map(n=>'src/'+n),'tools/build-assets.mjs','wrangler.jsonc'])digest.update(name+'\0').update(await readFile(new URL(name,root)));
digest.update(JSON.stringify(files)).update(headerText);
const buildId=digest.digest('hex').slice(0,20);
await mkdir(new URL('.wrangler/',root),{recursive:true});
await writeFile(new URL('.wrangler/static-assets.mjs',root),`// Generated by tools/build-assets.mjs. Edit public/ and rebuild.\nexport const files=${JSON.stringify(files)};\nexport const headers=${JSON.stringify(headers)};\nexport const buildId=${JSON.stringify(buildId)};\n`);
const config=JSON.parse(await readFile(new URL('wrangler.jsonc',root),'utf8'));
delete config.assets;
await writeFile(new URL('wrangler.fallback.jsonc',root),JSON.stringify(config,null,2)+'\n');
console.log(`Built ${names.length} bundled static routes (${buildId}).`);
